#!/usr/bin/env node
/**
 * Prepares a local SQLite development environment.
 *
 * Every deployed environment runs PostgreSQL. This script offers a local
 * database with no server to install or keep alive: a file on disk. The
 * schema is the canonical one - the same models, generated for SQLite - so
 * the application code, the API contracts and the business rules are shared
 * with production. Only the engine differs, and the few engine-specific
 * statements branch on it.
 *
 * Usage:
 *   pnpm dev:sqlite          prepare the file database and print the commands
 *   pnpm dev:sqlite --reset  recreate the file from scratch
 */
import { spawn } from "node:child_process"
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const localDirectory = join(rootDirectory, ".local")
const databasePath = join(localDirectory, "aipms.db")
// An absolute path: the API, the web app and the Prisma CLI each run from a
// different directory, and a relative file: URL would resolve differently in
// every one of them.
const databaseUrl = `file:${databasePath.replace(/\\/g, "/")}`
const envFile = join(rootDirectory, ".env.sqlite")
const reset = process.argv.includes("--reset")

function log(message) {
  console.log(message)
}

function fail(message) {
  console.error(message)
  process.exit(1)
}

async function run(command, args, { cwd, env } = {}) {
  const windowsPnpm = process.platform === "win32" && command === "pnpm"
  const executable = windowsPnpm ? (process.env.ComSpec ?? "cmd.exe") : command
  const parameters = windowsPnpm
    ? ["/d", "/s", "/c", ["pnpm", ...args].join(" ")]
    : args
  return new Promise((resolveResult, reject) => {
    const child = spawn(executable, parameters, {
      cwd,
      env,
      stdio: "inherit",
    })
    child.on("error", () =>
      reject(new Error(`Cannot launch ${command}; check installation and PATH`))
    )
    child.on("close", (code) =>
      code === 0
        ? resolveResult()
        : reject(
            new Error(
              `${command} ${args[0] ?? ""} failed; nothing was reset or cleaned up`
            )
          )
    )
  })
}

const sourceEnv = join(rootDirectory, ".env")
if (!existsSync(sourceEnv)) {
  fail(
    "No .env at the repository root. Copy .env.example to .env, fill it in, and run this script again."
  )
}

if (reset) {
  if (existsSync(databasePath)) {
    rmSync(databasePath, { force: true })
    log("[sqlite] removed the previous database file")
  }
  if (existsSync(envFile)) rmSync(envFile, { force: true })
}

mkdirSync(localDirectory, { recursive: true })

// The SQLite environment reuses every setting from .env and only swaps the
// database. AIPMS_ENV_FILE selects it for the API, web and agent processes.
const source = readFileSync(sourceEnv, "utf8")
const lines = source
  .split(/\r?\n/)
  .filter((line) => !/^\s*#?\s*DATABASE_URL\s*=/.test(line))
const envContent = [
  "# Generated by scripts/local-sqlite.mjs - local SQLite environment.",
  "# Select it with AIPMS_ENV_FILE=.env.sqlite; it is ignored by git.",
  ...lines,
  `DATABASE_URL=${databaseUrl}`,
  "",
].join("\n")
writeFileSync(envFile, envContent, "utf8")
log(`[sqlite] wrote .env.sqlite (DATABASE_URL=${databaseUrl})`)

const environment = {
  ...process.env,
  DATABASE_URL: databaseUrl,
  AIPMS_ENV_FILE: ".env.sqlite",
}

// The client must match the engine: generate it from the SQLite schema
// variant before the database is created.
await run("pnpm", ["--filter", "@workspace/db", "db:generate"], {
  cwd: rootDirectory,
  env: environment,
})
await run(
  "pnpm",
  ["--filter", "@workspace/db", "exec", "prisma", "db", "push"],
  {
    cwd: rootDirectory,
    env: environment,
  }
)
await run(
  "pnpm",
  ["--filter", "@workspace/db", "exec", "prisma", "db", "seed"],
  { cwd: rootDirectory, env: environment }
)

log("")
log("The local SQLite database is ready.")
log("")
log("Start the application with:")
log("  AIPMS_ENV_FILE=.env.sqlite pnpm dev")
log("")
log("The demo identities are seeded: maker@demo.aipms / demo-maker-123 and")
log("checker@demo.aipms / demo-checker-123.")
log("")
log("PostgreSQL remains the engine for every deployed environment; the")
log("production path is unchanged.")
